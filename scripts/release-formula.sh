#
# Regenerate Formula/vorssaint.rb for a published GitHub release.
#
# Expects the release assets produced by .github/workflows/ci.yml:
#   vorssaint-<tag>-macos-universal.tar.gz
#   vorssaint-<tag>-macos-universal.tar.gz.sha256
#
# Usage:
#   scripts/release-formula.sh v0.1.0
#   TAP_DIR=../homebrew-tap scripts/release-formula.sh v0.1.0
#
# Environment:
#   TAP_DIR                     optional Homebrew tap checkout; the generated
#                               formula is copied to $TAP_DIR/Formula/
#   VORSSAINT_RELEASE_BASE_URL  alternate release download base (used by tests)
set -euo pipefail

REPO="oldwinter/vorssaint-cli"
TAG="${1:-}"
if [[ -z "$TAG" || "$TAG" == "-h" || "$TAG" == "--help" ]]; then
  echo "usage: scripts/release-formula.sh vX.Y.Z" >&2
  exit 2
fi
[[ "$TAG" == v* ]] || TAG="v$TAG"
VERSION="${TAG#v}"
ASSET="vorssaint-${TAG}-macos-universal.tar.gz"
BASE="${VORSSAINT_RELEASE_BASE_URL:-https://github.com/${REPO}/releases/download/${TAG}}"
URL="${BASE%/}/${ASSET}"

SHA="$(curl -fsSL --retry 3 --connect-timeout 15 "$URL.sha256" | awk '{print $1}')"
if [[ ! "$SHA" =~ ^[0-9a-f]{64}$ ]]; then
  echo "release-formula: no valid sha256 at $URL.sha256 — publish the release first" >&2
  exit 1
fi

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FORMULA="$ROOT/Formula/vorssaint.rb"

cat > "$FORMULA" <<EOF
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Generated by scripts/release-formula.sh for ${TAG}. Do not edit by hand.
class Vorssaint < Formula
  desc "macOS power tools as a single terminal binary"
  homepage "https://github.com/${REPO}"
  url "${URL}"
  sha256 "${SHA}"
  version "${VERSION}"
  license "GPL-3.0-or-later"
  head "https://github.com/${REPO}.git", branch: "master"

  depends_on macos: :sonoma

  def install
    bin.install "vorssaint"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/vorssaint --version")
    assert_match "all checks passed", shell_output("#{bin}/vorssaint --selftest")
  end
end
EOF

echo "release-formula: wrote Formula/vorssaint.rb for ${TAG} (sha256 ${SHA})"

if [[ -n "${TAP_DIR:-}" ]]; then
  if [[ ! -d "$TAP_DIR/Formula" ]]; then
    echo "release-formula: $TAP_DIR does not look like a tap (no Formula/)" >&2
    exit 1
  fi
  cp "$FORMULA" "$TAP_DIR/Formula/vorssaint.rb"
  echo "release-formula: copied to $TAP_DIR/Formula/vorssaint.rb"
  echo "release-formula: update the tap README catalog, run scripts/test-all, open a PR"
fi
